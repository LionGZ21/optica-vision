create index ix_stock_articulo on stock(articulo_id);

create table movimiento_inventario (          -- KARDEX (inmutable)
  id              bigint generated by default as identity primary key,
  fecha           timestamptz not null default now(),
  articulo_id     bigint not null references articulo(id),
  bodega_id       bigint not null references bodega(id),
  tipo_movimiento varchar(30) not null check (tipo_movimiento in (
                    'ENTRADA','SALIDA','VENTA','DEFECTO',
                    'DEVOLUCION_CLIENTE','DEVOLUCION_PROVEEDOR',
                    'TRASLADO_SALIDA','TRASLADO_ENTRADA',
                    'ENTRADA_CONSIGNACION','DEVOLUCION_CONSIGNACION',
                    'CONSUMO_LABORATORIO','AJUSTE')),
  cantidad        numeric(14,3) not null check (cantidad <> 0),   -- (+) entra, (-) sale
  saldo_anterior  numeric(14,3) not null default 0,
  saldo_nuevo     numeric(14,3) not null default 0,
  costo_unitario  numeric(14,4),
  documento_tipo  varchar(30),
  documento_id    bigint,
  usuario_id      text,
  observacion     varchar(300)
);
create index ix_kardex_art_bod on movimiento_inventario(articulo_id, bodega_id, fecha desc);
create index ix_kardex_doc     on movimiento_inventario(documento_tipo, documento_id);

-- Protege el stock: solo el trigger del Kardex puede cambiar cantidades
create or replace function fn_stock_proteger() returns trigger
language plpgsql as $$
begin
  if coalesce(current_setting('app.kardex', true), '') <> 'on' then
    if tg_op = 'INSERT' and new.cantidad <> 0 then
      raise exception 'El stock solo puede modificarse mediante movimientos de Kardex';
    elsif tg_op = 'UPDATE' and new.cantidad is distinct from old.cantidad then
      raise exception 'El stock solo puede modificarse mediante movimientos de Kardex';
    end if;
  end if;
  return new;
end $$;

create trigger trg_stock_proteger
before insert or update on stock
for each row execute function fn_stock_proteger();

-- Núcleo del control de inventario
create or replace function fn_kardex_before_insert() returns trigger
language plpgsql as $$
declare
  v_bod_tipo text;
  v_bod_act  boolean;
  v_uso      text;
  v_art_act  boolean;
  v_saldo    numeric(14,3);
begin
  select tipo, activa into v_bod_tipo, v_bod_act from bodega where id = new.bodega_id;
  if not found or not v_bod_act then
    raise exception 'Bodega % inexistente o inactiva', new.bodega_id;
  end if;

  select uso, activo into v_uso, v_art_act from articulo where id = new.articulo_id;
  if not found or not v_art_act then
    raise exception 'Artículo % inexistente o inactivo', new.articulo_id;
  end if;

  -- Coherencia de signo según tipo de movimiento
  if new.tipo_movimiento in ('ENTRADA','DEVOLUCION_CLIENTE','TRASLADO_ENTRADA','ENTRADA_CONSIGNACION')
     and new.cantidad <= 0 then
    raise exception 'El movimiento % requiere cantidad positiva', new.tipo_movimiento;
  end if;
  if new.tipo_movimiento in ('SALIDA','VENTA','DEFECTO','DEVOLUCION_PROVEEDOR','TRASLADO_SALIDA',
                             'DEVOLUCION_CONSIGNACION','CONSUMO_LABORATORIO')
     and new.cantidad >= 0 then
    raise exception 'El movimiento % requiere cantidad negativa', new.tipo_movimiento;
  end if;

  -- Reglas de negocio
  if new.tipo_movimiento = 'VENTA' and v_bod_tipo <> 'VENTA' then
    raise exception 'Solo se puede vender desde bodegas de tipo VENTA (la de tránsito y las de almacén no venden)';
  end if;
  if new.tipo_movimiento = 'VENTA' and v_uso = 'CONSUMO_INTERNO' then
    raise exception 'El artículo % es de consumo interno y no puede venderse', new.articulo_id;
  end if;
  if v_bod_tipo = 'TRANSITO' and new.tipo_movimiento not in ('TRASLADO_ENTRADA','TRASLADO_SALIDA') then
    raise exception 'La bodega de tránsito solo admite movimientos de traslado entre sucursales';
  end if;

  -- Habilita escritura sobre stock durante esta transacción
  perform set_config('app.kardex', 'on', true);

  insert into stock(bodega_id, articulo_id, cantidad)
  values (new.bodega_id, new.articulo_id, 0)
  on conflict (bodega_id, articulo_id) do nothing;

  select cantidad into v_saldo
    from stock where bodega_id = new.bodega_id and articulo_id = new.articulo_id
    for update;                                   -- bloqueo: evita carreras de concurrencia

  new.saldo_anterior := v_saldo;
  new.saldo_nuevo    := v_saldo + new.cantidad;

  if new.saldo_nuevo < 0 then
    raise exception 'Stock insuficiente (artículo %, bodega %): disponible %, solicitado %',
      new.articulo_id, new.bodega_id, v_saldo, abs(new.cantidad)
      using errcode = '23514';
  end if;

  update stock set cantidad = new.saldo_nuevo, updated_at = now()
   where bodega_id = new.bodega_id and articulo_id = new.articulo_id;

  return new;
end $$;

create trigger trg_kardex_before_insert
before insert on movimiento_inventario
for each row execute function fn_kardex_before_insert();

-- El Kardex es inmutable
create or replace function fn_kardex_inmutable() returns trigger
language plpgsql as $$
begin
  raise exception 'El Kardex es inmutable: para corregir registre un movimiento de AJUSTE';
end $$;

create trigger trg_kardex_inmutable
before update or delete on movimiento_inventario
for each row execute function fn_kardex_inmutable();

