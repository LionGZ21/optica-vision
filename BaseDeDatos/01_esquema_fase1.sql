  detalle_id       bigint not null references consignacion_detalle(id),
  cantidad         numeric(14,3) not null check (cantidad > 0),
  costo_unitario   numeric(14,4) not null check (costo_unitario >= 0)
);

-- Al liquidar, se acumula lo vendido en el detalle de consignación
create or replace function fn_liquidacion_acumular() returns trigger
language plpgsql as $$
begin
  update consignacion_detalle
     set cantidad_vendida = cantidad_vendida + new.cantidad
   where id = new.detalle_id;            -- el CHECK impide liquidar más de lo disponible
  update consignacion_liquidacion
     set total = total + (new.cantidad * new.costo_unitario)
   where id = new.liquidacion_id;
  return new;
end $$;

create trigger trg_liquidacion_acumular
after insert on consignacion_liquidacion_detalle
for each row execute function fn_liquidacion_acumular();

create or replace function fn_recibir_consignacion(p_id bigint, p_usuario text) returns void
language plpgsql as $$
declare c consignacion%rowtype; d record;
begin
  select * into c from consignacion where id = p_id for update;
  if not found then raise exception 'Consignación % no existe', p_id; end if;
  if c.estado <> 'BORRADOR' then raise exception 'Solo se puede recibir una consignación en BORRADOR'; end if;

  for d in select * from consignacion_detalle where consignacion_id = p_id loop
    insert into movimiento_inventario(articulo_id, bodega_id, tipo_movimiento, cantidad, costo_unitario,
                                      documento_tipo, documento_id, usuario_id)
    values (d.articulo_id, c.bodega_id, 'ENTRADA_CONSIGNACION', d.cantidad_recibida, d.costo_unitario,
            'CONSIGNACION', c.id, p_usuario);
  end loop;
  update consignacion set estado = 'ABIERTA' where id = p_id;
end $$;

create or replace function fn_devolver_consignacion(p_detalle_id bigint, p_cantidad numeric, p_usuario text) returns void
language plpgsql as $$
declare d consignacion_detalle%rowtype; c consignacion%rowtype;
begin
  select * into d from consignacion_detalle where id = p_detalle_id for update;
  if not found then raise exception 'Detalle % no existe', p_detalle_id; end if;
  select * into c from consignacion where id = d.consignacion_id;
  if c.estado <> 'ABIERTA' then raise exception 'La consignación no está ABIERTA'; end if;
  if p_cantidad <= 0 or p_cantidad > (d.cantidad_recibida - d.cantidad_vendida - d.cantidad_devuelta) then
    raise exception 'Cantidad a devolver inválida';
  end if;

  insert into movimiento_inventario(articulo_id, bodega_id, tipo_movimiento, cantidad, costo_unitario,
                                    documento_tipo, documento_id, usuario_id)
  values (d.articulo_id, c.bodega_id, 'DEVOLUCION_CONSIGNACION', -p_cantidad, d.costo_unitario,
          'CONSIGNACION', c.id, p_usuario);

  update consignacion_detalle set cantidad_devuelta = cantidad_devuelta + p_cantidad where id = p_detalle_id;
end $$;

