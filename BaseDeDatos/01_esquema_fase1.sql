-- Descuenta del inventario la montura y los cristales en blanco de la orden
create or replace function fn_consumir_orden_lab(p_orden_id bigint, p_usuario text) returns void
language plpgsql as $$
declare o orden_trabajo_lab%rowtype; d record; v_mov bigint;
begin
  select * into o from orden_trabajo_lab where id = p_orden_id for update;
  if not found then raise exception 'Orden % no existe', p_orden_id; end if;
  if o.estado not in ('PENDIENTE','EN_PROCESO') then
    raise exception 'La orden está en estado %, no admite consumo', o.estado;
  end if;

  for d in select * from orden_trabajo_lab_detalle where orden_id = p_orden_id and not consumido loop
    insert into movimiento_inventario(articulo_id, bodega_id, tipo_movimiento, cantidad,
                                      documento_tipo, documento_id, usuario_id)
    values (d.articulo_id, o.bodega_consumo_id, 'CONSUMO_LABORATORIO', -d.cantidad, 'ORDEN_LAB', o.id, p_usuario)
    returning id into v_mov;

    update orden_trabajo_lab_detalle set consumido = true, movimiento_id = v_mov where id = d.id;
  end loop;

  update orden_trabajo_lab
     set estado = 'EN_PROCESO', fecha_inicio = coalesce(fecha_inicio, now())
   where id = p_orden_id;
end $$;

