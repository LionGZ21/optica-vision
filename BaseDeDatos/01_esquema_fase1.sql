create or replace function fn_auditoria() returns trigger
language plpgsql as $$
declare v_row jsonb;
begin
  v_row := to_jsonb(case when tg_op = 'DELETE' then old else new end);
  insert into auditoria_log(tabla, registro_id, operacion, datos_anteriores, datos_nuevos, usuario_id)
  values (tg_table_name, v_row->>'id', tg_op,
          case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end,
          case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) end,
          nullif(current_setting('app.usuario', true), ''));
  return null;
end $$;

-- ---------------------------------------------------------------------
-- 12. TRIGGERS EN LOTE: updated_at, auditoría y RLS
-- ---------------------------------------------------------------------
do $$
declare r record;
begin
  -- updated_at automático
  for r in
    select c.table_name
      from information_schema.columns c
      join information_schema.tables t
        on t.table_schema = c.table_schema and t.table_name = c.table_name and t.table_type = 'BASE TABLE'
     where c.table_schema = 'public' and c.column_name = 'updated_at'
  loop
    execute format('drop trigger if exists trg_%1$s_updated_at on public.%1$I', r.table_name);
    execute format('create trigger trg_%1$s_updated_at before update on public.%1$I
                    for each row execute function fn_set_updated_at()', r.table_name);
  end loop;

  -- auditoría en tablas críticas
  for r in
    select unnest(array['articulo','proveedor','lista_precio','sucursal','bodega','traslado',
                        'paciente','receta','consulta','venta','orden_trabajo_lab','consignacion']) as table_name
  loop
    execute format('drop trigger if exists trg_%1$s_auditoria on public.%1$I', r.table_name);
    execute format('create trigger trg_%1$s_auditoria after insert or update or delete on public.%1$I
                    for each row execute function fn_auditoria()', r.table_name);
  end loop;

  -- Seguridad: RLS activado sin políticas => la Data API de Supabase (anon/authenticated)
  -- queda bloqueada. Nuestro backend ASP.NET se conecta con el rol postgres (BYPASSRLS).
  for r in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', r.tablename);
  end loop;
end $$;

