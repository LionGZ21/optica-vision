-- Histórico de precios (lo llenan los triggers)
create table historial_precio (
  id               bigint generated by default as identity primary key,
  tipo_precio      varchar(10) not null check (tipo_precio in ('VENTA','COSTO')),
  articulo_id      bigint not null references articulo(id),
  lista_precio_id  bigint references lista_precio(id),
  proveedor_id     bigint references proveedor(id),
  unidad_medida_id bigint references unidad_medida(id),
  precio_anterior  numeric(14,4),
  precio_nuevo     numeric(14,4) not null,
  operacion        varchar(10) not null,
  usuario_id       text,
  fecha            timestamptz not null default now()
);
create index ix_histprecio_articulo on historial_precio(articulo_id, fecha desc);

create or replace function fn_hist_precio_venta() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' or new.precio is distinct from old.precio then
    insert into historial_precio(tipo_precio, articulo_id, lista_precio_id, unidad_medida_id,
                                 precio_anterior, precio_nuevo, operacion, usuario_id)
    values ('VENTA', new.articulo_id, new.lista_precio_id, new.unidad_medida_id,
            case when tg_op = 'UPDATE' then old.precio end, new.precio, tg_op, new.modificado_por);
  end if;
  return new;
end $$;

create trigger trg_articulo_precio_hist
after insert or update on articulo_precio
for each row execute function fn_hist_precio_venta();

