  telefono   varchar(30),
  activa     boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table bodega (
  id             bigint generated by default as identity primary key,
  sucursal_id    bigint references sucursal(id),
  codigo         varchar(20)  not null unique,
  nombre         varchar(120) not null,
  tipo           varchar(20)  not null check (tipo in ('VENTA','ALMACEN','TRANSITO')),
  placa_vehiculo varchar(20),                       -- solo para camiones (TRANSITO)
  activa         boolean not null default true,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  -- La bodega de tránsito NO pertenece a una sucursal; las demás sí.
  constraint ck_bodega_sucursal check (
    (tipo = 'TRANSITO' and sucursal_id is null) or (tipo <> 'TRANSITO' and sucursal_id is not null)
  )
);

create or replace function fn_bodega_validar() returns trigger
language plpgsql as $$
declare v_tipo_suc text;
begin
  if new.tipo = 'VENTA' then
    select tipo into v_tipo_suc from sucursal where id = new.sucursal_id;
    if v_tipo_suc is distinct from 'VENTA' then
      raise exception 'Una bodega de VENTA solo puede pertenecer a una sucursal de tipo VENTA';
    end if;
  end if;
  return new;
end $$;

create trigger trg_bodega_validar
before insert or update on bodega
for each row execute function fn_bodega_validar();

