create or replace view vw_articulos_bajo_minimo with (security_invoker = true) as
select a.id, a.codigo, a.nombre, a.stock_minimo,
       coalesce(sum(s.cantidad) filter (where b.tipo <> 'TRANSITO'), 0) as stock_total
  from articulo a
  left join stock s  on s.articulo_id = a.id
  left join bodega b on b.id = s.bodega_id
 where a.activo and a.stock_minimo > 0
 group by a.id
having coalesce(sum(s.cantidad) filter (where b.tipo <> 'TRANSITO'), 0) < a.stock_minimo;

