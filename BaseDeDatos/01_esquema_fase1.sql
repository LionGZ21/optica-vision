-- 6. TRASLADOS ENTRE SUCURSALES (vía Bodega de Tránsito)
-- ---------------------------------------------------------------------
create table traslado (
  id                 bigint generated by default as identity primary key,
  numero             varchar(20) not null unique default ('TR-' || lpad(nextval('seq_traslado')::text, 8, '0')),
  bodega_origen_id   bigint not null references bodega(id),
  bodega_transito_id bigint not null references bodega(id),
  bodega_destino_id  bigint not null references bodega(id),
  estado             varchar(20) not null default 'BORRADOR'
                     check (estado in ('BORRADOR','EN_TRANSITO','RECIBIDO','CANCELADO')),
  observacion        varchar(300),
  creado_por         text,
  despachado_por     text,
  recibido_por       text,
  fecha_creacion     timestamptz not null default now(),
  fecha_despacho     timestamptz,
  fecha_recepcion    timestamptz,
  updated_at         timestamptz not null default now(),
  check (bodega_origen_id <> bodega_destino_id)
);

create table traslado_detalle (
  id          bigint generated by default as identity primary key,
  traslado_id bigint not null references traslado(id) on delete cascade,
  articulo_id bigint not null references articulo(id),
  cantidad    numeric(14,3) not null check (cantidad > 0),
  unique (traslado_id, articulo_id)
);

create or replace function fn_traslado_validar() returns trigger
language plpgsql as $$
declare t_o text; t_t text; t_d text;
begin
  select tipo into t_o from bodega where id = new.bodega_origen_id;
  select tipo into t_t from bodega where id = new.bodega_transito_id;
  select tipo into t_d from bodega where id = new.bodega_destino_id;
  if t_t is distinct from 'TRANSITO' then
    raise exception 'La bodega intermedia del traslado debe ser de tipo TRANSITO';
  end if;
  if t_o = 'TRANSITO' or t_d = 'TRANSITO' then
    raise exception 'Origen y destino no pueden ser la bodega de tránsito';
  end if;
  return new;
end $$;

create trigger trg_traslado_validar
before insert or update on traslado
for each row execute function fn_traslado_validar();

-- Despacho: origen -> tránsito
create or replace function fn_despachar_traslado(p_traslado_id bigint, p_usuario text) returns void
language plpgsql as $$
declare t traslado%rowtype; d record;
begin
  select * into t from traslado where id = p_traslado_id for update;
  if not found then raise exception 'Traslado % no existe', p_traslado_id; end if;
  if t.estado <> 'BORRADOR' then raise exception 'Solo se puede despachar un traslado en BORRADOR'; end if;
  if not exists (select 1 from traslado_detalle where traslado_id = p_traslado_id) then
    raise exception 'El traslado no tiene artículos';
  end if;

  for d in select * from traslado_detalle where traslado_id = p_traslado_id loop
    insert into movimiento_inventario(articulo_id, bodega_id, tipo_movimiento, cantidad, documento_tipo, documento_id, usuario_id)
    values (d.articulo_id, t.bodega_origen_id,   'TRASLADO_SALIDA',  -d.cantidad, 'TRASLADO', t.id, p_usuario),
           (d.articulo_id, t.bodega_transito_id, 'TRASLADO_ENTRADA',  d.cantidad, 'TRASLADO', t.id, p_usuario);
  end loop;

  update traslado set estado = 'EN_TRANSITO', fecha_despacho = now(), despachado_por = p_usuario
   where id = p_traslado_id;
end $$;

-- Recepción: tránsito -> destino
create or replace function fn_recibir_traslado(p_traslado_id bigint, p_usuario text) returns void
language plpgsql as $$
declare t traslado%rowtype; d record;
begin
  select * into t from traslado where id = p_traslado_id for update;
  if not found then raise exception 'Traslado % no existe', p_traslado_id; end if;
  if t.estado <> 'EN_TRANSITO' then raise exception 'Solo se puede recibir un traslado EN_TRANSITO'; end if;

  for d in select * from traslado_detalle where traslado_id = p_traslado_id loop
    insert into movimiento_inventario(articulo_id, bodega_id, tipo_movimiento, cantidad, documento_tipo, documento_id, usuario_id)
    values (d.articulo_id, t.bodega_transito_id, 'TRASLADO_SALIDA',  -d.cantidad, 'TRASLADO', t.id, p_usuario),
           (d.articulo_id, t.bodega_destino_id,  'TRASLADO_ENTRADA',  d.cantidad, 'TRASLADO', t.id, p_usuario);
  end loop;

  update traslado set estado = 'RECIBIDO', fecha_recepcion = now(), recibido_por = p_usuario
   where id = p_traslado_id;
end $$;

