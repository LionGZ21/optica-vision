create or replace view vw_articulo_taxonomia with (security_invoker = true) as
select a.id as articulo_id, a.codigo, a.nombre, a.activo, a.uso, a.tipo_articulo,
       d.nombre as departamento, s.nombre as seccion, f.nombre as familia, sf.nombre as subfamilia,
