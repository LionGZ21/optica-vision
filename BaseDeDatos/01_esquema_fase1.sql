create or replace function fn_confirmar_venta(p_venta_id bigint, p_usuario text) returns void
language plpgsql as $$
declare v venta%rowtype; d record;
begin
  select * into v from venta where id = p_venta_id for update;
  if not found then raise exception 'Venta % no existe', p_venta_id; end if;
  if v.estado <> 'BORRADOR' then raise exception 'Solo se puede confirmar una venta en BORRADOR'; end if;
  if not exists (select 1 from venta_detalle where venta_id = p_venta_id) then
    raise exception 'La venta no tiene líneas';
  end if;

  for d in
    select vd.*, um.factor_base
      from venta_detalle vd join unidad_medida um on um.id = vd.unidad_medida_id
     where vd.venta_id = p_venta_id
  loop
    insert into movimiento_inventario(articulo_id, bodega_id, tipo_movimiento, cantidad,
                                      documento_tipo, documento_id, usuario_id)
    values (d.articulo_id, v.bodega_id, 'VENTA', -(d.cantidad * d.factor_base), 'VENTA', v.id, p_usuario);
  end loop;

  update venta set estado = 'CONFIRMADA' where id = p_venta_id;
end $$;

